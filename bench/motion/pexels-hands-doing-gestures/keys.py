"""Keys read off the reference at 0.5 s steps. Coordinates are reference pixels at 480x270.
A = left hand (screen left, forearm in front), B = right hand (screen right).
H(wrist, knuckles, arm, palm, fingers): arm is where the forearm leaves the frame bottom
(x, 270) or an angle in degrees from vertical."""
import math

DURATION = 18.2
MOVE_SCALE = 1.7
EASE = "smooth"
ZA, ZB = 0.035, -0.035  # depth: left forearm in front


def H(w, kn, arm, palm, fingers, z=None, **kw):
    dx, dy = kn[0] - w[0], w[1] - kn[1]
    hd = math.degrees(math.atan2(dx, dy))
    if isinstance(arm, tuple):
        ax, ay = w[0] - arm[0], arm[1] - w[1]
        arm = math.degrees(math.atan2(ax, ay))
    d = {"w": (w[0], w[1], z), "hd": hd, "hz": kw.pop("hz", 0.0), "arm": arm, "palm": palm}
    d.update(fingers)
    d.update(kw)
    return d


def A(*a, **k):
    h = H(*a, **k)
    h["w"] = (h["w"][0], h["w"][1], ZA if h["w"][2] is None else h["w"][2])
    return h


def B(*a, **k):
    h = H(*a, **k)
    h["w"] = (h["w"][0], h["w"][1], ZB if h["w"][2] is None else h["w"][2])
    return h


