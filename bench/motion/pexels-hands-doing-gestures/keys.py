def F(i, m, r, p, th=None, cup=None):
    """each finger [mcp_flex, pip_flex(, mcp_abd)]"""
    d = {"index": i, "middle": m, "ring": r, "pinky": p}
    d["thumb"] = th or TH_REL
    if cup is not None:
        d["cup"] = cup
    return d


